/**
 * 재미 도식을 AI에게 건네 실존주의적 성찰을 요청하는 프롬프트.
 *
 * 이 앱의 목적은 재미 자체가 아니라 실존주의적 삶의 태도를 완성해 가는 것이다.
 * 그래서 프롬프트는 AI가 평가하거나 처방하기보다, 유저가 스스로 돌아볼 거리를 건네도록 설계한다.
 */
import { statusLabel } from './card';
import type { FunSchema, SchemaStep } from './schema';

const STEP_TAG: Record<SchemaStep['kind'], string> = {
  action: '',
  emotion: '[감정] ',
  utility: '[효용] ',
  money: '[돈] ',
  worry: '[걱정] ',
  fact: '[사실] ',
  protects: '[지키려는 것] ',
  mine: '[내 몫] ',
  notMine: '[내 몫 아님] ',
  fun: '',
};

const CARD_HEADING = {
  action: (title: string) => `행동 카드: ${title}`,
  money: () => '돈 카드 (돈이 어떻게 재미로 이어지는가)',
  worry: (title: string) => `걱정 카드: ${title}`,
};

function renderPath(path: SchemaStep[]): string {
  return path.map((s) => `${STEP_TAG[s.kind]}${s.label}`).join(' → ');
}

/** 사람과 AI가 모두 읽기 쉬운 텍스트 형태의 재미 도식 */
export function renderSchemaText(schema: FunSchema): string {
  const { summary } = schema;
  const lines: string[] = [
    `- 행동 카드 ${summary.actionCards}개 중 재미까지 이어진 카드 ${summary.connectedCards}개` +
      (summary.viaMoneyCards ? ` (그중 돈을 거쳐 이어진 카드 ${summary.viaMoneyCards}개)` : ''),
    `- 행동 카드에 만든 박스: 감정 ${summary.emotionBoxes}개, 효용 ${summary.utilityBoxes}개, 돈 ${summary.moneyBoxes}개, 걱정 ${summary.worryBoxes}개`,
  ];
  if (summary.worryCards) {
    lines.push(`- 걱정 카드 ${summary.worryCards}개 중 '그럼에도'까지 정리한 카드 ${summary.resolvedWorryCards}개`);
  }
  if (summary.moneyRewardActions.length) {
    lines.push(`- 돈을 보상(도착점)으로 둔 행동: ${summary.moneyRewardActions.join(', ')}`);
  }
  if (summary.recurring.length) {
    lines.push(
      `- 여러 행동에서 반복해서 나타난 것: ` +
        summary.recurring.map((r) => `"${r.label}"(${r.cards.join(', ')})`).join(', '),
    );
  }

  for (const card of schema.cards) {
    lines.push('', `### ${CARD_HEADING[card.kind](card.title)} — ${statusLabel(card.status, card.kind)}`);
    if (card.origins?.length) {
      lines.push(`- 이 걱정이 생겨난 곳: ` + card.origins.map((o) => `${o.card} 카드의 "${o.from}"`).join(', '));
    }
    if (card.paths.length) {
      lines.push(...card.paths.map((p) => `- ${renderPath(p)}`));
    } else {
      lines.push('- (아직 이어진 경로 없음)');
    }
    if (card.unconnected.length) {
      lines.push(
        `- 아직 어디에도 잇지 못한 박스: ` +
          card.unconnected.map((b) => `${STEP_TAG[b.kind]}${b.label}`).join(', '),
      );
    }
    if (card.kind === 'worry') {
      lines.push(card.resolve ? `- 그럼에도 나는: ${card.resolve}` : `- 그럼에도 나는: (아직 적지 않음)`);
    }
  }
  return lines.join('\n');
}

